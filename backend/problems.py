def evaluate_problem_submission(problem: dict[str, Any], solution_text: str) -> dict[str, Any]:
    """Evaluates learner problem submission against required keywords and structural completeness."""
    text_clean = solution_text.strip().casefold()
    word_count = len(solution_text.split())

    if word_count < 15:
        return {
            "status": "needs_revision",
            "score": 25,
            "feedback": "Solution is too brief. Provide a thorough engineering analysis with root cause, code/config remedy, and verification steps.",
            "passed": False,
        }

    expected_kw = problem.get("expected_keywords", [])
    matched_kw = [kw for kw in expected_kw if kw.casefold() in text_clean]
    match_ratio = len(matched_kw) / len(expected_kw) if expected_kw else 1.0

    if match_ratio >= 0.6:
        score = int(75 + (match_ratio * 25))
        return {
            "status": "completed",
            "score": min(score, 100),
            "feedback": f"Excellent engineering solution! Successfully identified core concepts ({', '.join(matched_kw)}). Meets production criteria.",
            "passed": True,
        }
    else:
        missing_kw = [kw for kw in expected_kw if kw not in matched_kw]
        return {
            "status": "needs_revision",
            "score": int(match_ratio * 60),
            "feedback": f"Partially addressed. Ensure your answer directly addresses production details such as: {', '.join(missing_kw[:3])}.",
            "passed": False,
        }
